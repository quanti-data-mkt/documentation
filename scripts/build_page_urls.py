#!/usr/bin/env python3
"""Build reference/page-urls.json: the public URL of every page, from SUMMARY.md.

GitBook builds a page URL from the navigation, not from the file path:

    URL = slug of the "## Group" heading (if any)
        + slugs of the parent pages
        + slug of the page (file name without .md, or the folder name for a README.md)

So "connectors/marketing-connectors/google-ads.md" is published at
https://docs.quanti.io/connect/connectors/google-ads. The QUANTI: app reads this
file (like reference/help-map.json) to link each help fragment to its page on
docs.quanti.io, instead of guessing the URL from the file path.

After any change to SUMMARY.md, run:

    python3 scripts/build_page_urls.py          # rewrite reference/page-urls.json
    python3 scripts/build_page_urls.py --check  # exit 1 if the file is out of date

Never rename or move a published .md file: change titles in SUMMARY.md instead.
"""
import json
import os
import re
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUMMARY = os.path.join(ROOT, 'SUMMARY.md')
OUT = os.path.join(ROOT, 'reference', 'page-urls.json')
BASE = 'https://docs.quanti.io/'

LINK = re.compile(r'^(\s*)[*-]\s+\[(.+?)\]\((.+?\.md)(?:\s+".*")?\)')
GROUP = re.compile(r'^##\s+(.+?)\s*$')


def slugify(text):
    text = unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode()
    return re.sub(r'[^A-Za-z0-9]+', '-', text.lower()).strip('-')


def page_slug(path):
    parts = path.strip('./').split('/')
    if parts[-1].lower() == 'readme.md':
        return parts[-2] if len(parts) > 1 else 'readme'
    return re.sub(r'\.md$', '', parts[-1])


def page_urls(summary):
    """{file path: public URL} for every page listed in SUMMARY.md."""
    urls, group, parents = {}, None, []
    for line in summary.splitlines():
        heading = GROUP.match(line)
        if heading:
            group, parents = slugify(heading.group(1)), []
            continue
        link = LINK.match(line)
        if not link:
            continue
        indent = len(link.group(1).replace('\t', '    '))
        path = link.group(3).lstrip('./')
        while parents and parents[-1][0] >= indent:
            parents.pop()
        slug = page_slug(path)
        segments = ([group] if group else []) + [s for _, s in parents] + [slug]
        urls[path] = BASE + '/'.join(segments)
        parents.append((indent, slug))
    return urls


def render(urls):
    data = {
        '_how_to': [
            'Generated by scripts/build_page_urls.py from SUMMARY.md: do not edit by hand.',
            'Key: page file in this repository. Value: its public URL on docs.quanti.io.',
            'After any change to SUMMARY.md, run: python3 scripts/build_page_urls.py',
        ],
    }
    data.update(dict(sorted(urls.items())))
    return json.dumps(data, indent=1, ensure_ascii=False) + '\n'


def main():
    with open(SUMMARY, encoding='utf-8') as f:
        content = render(page_urls(f.read()))
    current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if '--check' in sys.argv[1:]:
        if current != content:
            print('reference/page-urls.json is out of date: run python3 scripts/build_page_urls.py')
            sys.exit(1)
        print('reference/page-urls.json is up to date.')
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f'reference/page-urls.json: {len(json.loads(content)) - 1} pages.')


if __name__ == '__main__':
    main()
